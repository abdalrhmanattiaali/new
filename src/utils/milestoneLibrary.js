function findClosestEntry(ageInMonths) {
  const sorted = [...milestoneLibrary].sort((a, b) => a.month - b.month);
  let selected = sorted[0];
  for (const entry of sorted) {
    if (ageInMonths >= entry.month) {
      selected = entry;
    } else {
      break;
    }
  }
  return selected;
}

